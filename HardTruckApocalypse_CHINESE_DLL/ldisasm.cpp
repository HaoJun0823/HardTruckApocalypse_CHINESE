const uint8_t kPrefixes[] = {
    0xF0, 0xF2, 0xF3, 0x2E, 0x36, 0x3E, 0x26, 0x64, 0x65, 0x66, 0x67
};

bool IsPrefix(uint8_t b) {
    for (int i = 0; i < (int)sizeof(kPrefixes); ++i)
        if (kPrefixes[i] == b) return true;
    return false;
}

